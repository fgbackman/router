// Package pf renders and loads the router's packet filter rules.
//
// Rules are loaded into the anchor "com.apple/router". The stock macOS
// /etc/pf.conf already evaluates nat-anchor, rdr-anchor and anchor
// "com.apple/*", so nothing in /etc/pf.conf has to be edited and
// macOS updates won't drop our rules from the main ruleset.
package pf

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/fgbackman/router/internal/config"
)

const Anchor = "com.apple/router"

// Render produces the anchor ruleset for cfg.
func Render(cfg *config.Config) (string, error) {
	if err := cfg.Validate(); err != nil {
		return "", err
	}
	lan, _ := cfg.LANPrefix()
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

	w("# Generated by router. Do not edit; changes are overwritten on apply.")
	w("wan_if = \"%s\"", cfg.WAN.Interface)
	w("lan_if = \"%s\"", cfg.LAN.Interface)
	w("lan_net = \"%s\"", lan.Masked())
	w("")
	w("# --- Translation ---")
	w("nat on $wan_if inet from $lan_net to any -> ($wan_if)")
	for _, f := range cfg.Firewall.PortForwards {
		label := ""
		if f.Name != "" {
			label = " # " + f.Name
		}
		w("rdr pass on $wan_if inet proto %s from any to ($wan_if) port %d -> %s port %d%s",
			protoList(f.Protocol), f.ExternalPort, f.InternalIP, f.InternalPort, label)
	}
	w("")
	w("# --- Filtering ---")
	if cfg.Firewall.BlockInbound {
		w("block in log on $wan_if inet all")
		w("# DHCP replies for the Mac's own WAN lease")
		w("pass in quick on $wan_if inet proto udp from any port 67 to any port 68")
		if cfg.Firewall.AllowPing {
			w("pass in on $wan_if inet proto icmp all icmp-type echoreq keep state")
		}
		for _, p := range cfg.Firewall.OpenPorts {
			proto, port, _ := config.ParseProtoPort(p)
			w("pass in on $wan_if inet proto %s from any to ($wan_if) port %d keep state", proto, port)
		}
	}
	w("pass out on $wan_if inet all keep state")
	w("pass in on $lan_if all keep state")
	w("pass out on $lan_if all keep state")
	return b.String(), nil
}

func protoList(p string) string {
	if p == "both" {
		return "{ tcp udp }"
	}
	return p
}

// Runner executes pfctl. Tests replace it.
var Runner = func(stdin []byte, args ...string) ([]byte, error) {
	cmd := exec.Command("/sbin/pfctl", args...)
	if stdin != nil {
		cmd.Stdin = bytes.NewReader(stdin)
	}
	out, err := cmd.CombinedOutput()
	if err != nil {
		return out, fmt.Errorf("pfctl %s: %w: %s", strings.Join(args, " "), err, strings.TrimSpace(string(out)))
	}
	return out, nil
}

// Check parses rules without loading them.
func Check(rules string) error {
	_, err := Runner([]byte(rules), "-n", "-a", Anchor, "-f", "-")
	return err
}

// Load writes rules to stateDir for inspection, then replaces the anchor's
// contents and enables pf. It returns the pf enable token, which Disable
// releases so pf stays on if something else (e.g. the macOS firewall) needs it.
func Load(stateDir, rules string) (token string, err error) {
	if err := os.WriteFile(filepath.Join(stateDir, "pf.rules"), []byte(rules), 0o644); err != nil {
		return "", err
	}
	if err := Check(rules); err != nil {
		return "", err
	}
	if _, err := Runner([]byte(rules), "-a", Anchor, "-f", "-"); err != nil {
		return "", err
	}
	out, err := Runner(nil, "-E")
	if err != nil {
		return "", err
	}
	return parseToken(out), nil
}

// Reload swaps the anchor contents without touching the enable token.
func Reload(stateDir, rules string) error {
	if err := os.WriteFile(filepath.Join(stateDir, "pf.rules"), []byte(rules), 0o644); err != nil {
		return err
	}
	if err := Check(rules); err != nil {
		return err
	}
	_, err := Runner([]byte(rules), "-a", Anchor, "-f", "-")
	return err
}

// Flush removes our rules and NAT states and releases the enable token.
func Flush(token string) error {
	_, err := Runner(nil, "-a", Anchor, "-F", "all")
	if token != "" {
		if _, err2 := Runner(nil, "-X", token); err == nil {
			err = err2
		}
	}
	return err
}

var tokenRE = regexp.MustCompile(`Token\s*:\s*(\d+)`)

func parseToken(out []byte) string {
	if m := tokenRE.FindSubmatch(out); m != nil {
		return string(m[1])
	}
	return ""
}

// Status returns pfctl's view of the anchor for display.
func Status() string {
	var b strings.Builder
	if out, err := Runner(nil, "-s", "info"); err == nil {
		if line, _, ok := strings.Cut(string(out), "\n"); ok {
			b.WriteString(strings.TrimSpace(line) + "\n")
		}
	}
	for _, kind := range []string{"nat", "rules"} {
		out, err := Runner(nil, "-a", Anchor, "-s", kind)
		if err != nil {
			fmt.Fprintf(&b, "(%s unavailable: %v)\n", kind, err)
			continue
		}
		b.Write(out)
	}
	return b.String()
}
